// Pote only ever shipped a KR/EN toggle in the UI — the other eight
// languages (ja/zh/es/fr/de/pt/ar/id) were a flag-selector experiment that
// did reach production, but keeping every future piece of copy translated
// into all ten turned out to cost far more time than it was worth for a
// two-person, Korean-first operation. Removed 2026-09-19 in favor of a
// plain KR/EN toggle; see HANDOFF.md for the removal note.
export type Lang = "ko" | "en";

type LanguageContextValue = { lang: Lang; toggle: () => void; setLang: (lang: Lang) => void; rates: Record<string, number> };

const FALLBACK_RATES = { KRW: 1, USD: 0.00073 };

const LanguageContext = createContext<LanguageContextValue | null>(null);

const STORAGE_KEY = "pote-lang";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ko");
  const [rates, setRates] = useState<Record<string, number>>(FALLBACK_RATES);

  useEffect(() => {
    if (lang !== "en") return;
    const controller = new AbortController();
    fetch("/api/exchange-rates", { signal: controller.signal })
      .then((response) => response.json())
      .then((data) => { if (data?.rates) setRates({ ...FALLBACK_RATES, ...data.rates }); })
      .catch(() => undefined);
    return () => controller.abort();
  }, [lang]);

  useEffect(() => {
    // One-time sync from localStorage after mount, kept separate from the
    // initial render so the server-rendered "ko" markup matches on hydration.
    // Priority: an explicit `?lang=en|ko` on the link (our English social
    // captions use it), then the visitor's saved choice, then the browser
    // language — so someone abroad opening a shared link isn't dropped onto
    // a Korean page with no idea there's an EN toggle.
    try {
      const param = new URLSearchParams(window.location.search).get("lang");
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (param === "ko" || param === "en") {
        window.localStorage.setItem(STORAGE_KEY, param);
        // eslint-disable-next-line react-hooks/set-state-in-effect
        setLangState(param);
      } else if (saved === "ko" || saved === "en") {
        setLangState(saved);
      } else if (!window.navigator.language.toLowerCase().startsWith("ko")) {
        setLangState("en");
      }
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (next: Lang) => {
    setLangState(next);
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch {}
  };
  const toggle = () => setLang(lang === "ko" ? "en" : "ko");

  return <LanguageContext.Provider value={{ lang, toggle, setLang, rates }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}

