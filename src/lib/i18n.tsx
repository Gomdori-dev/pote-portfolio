export type DictKey = keyof typeof dict;

export function formatWorkCount(count: number, lang: Lang): string {
  switch (lang) {
    case "ko": return `작품 ${count}점`;
    case "en": return `${count} ${count === 1 ? "work" : "works"}`;
  }
}

export function formatExhibitionCount(count: number, lang: Lang): string {
  switch (lang) {
    case "ko": return `${count}개의 전시`;
    case "en": return `${count} ${count === 1 ? "exhibition" : "exhibitions"}`;
  }
}

export function useT() {
 const { lang } = useLanguage();
 return (key: DictKey) => dict[key][lang];
}

export function usePrice() {
  const { lang, rates } = useLanguage();
  return (valueKrw: number) => formatLocalizedPrice(valueKrw, lang, rates);
}

export function T({ k }: { k: DictKey }) {
  const t = useT();
  const parts = t(k).split("\n");
  return (
    <>
      {parts.map((part, i) => (
        <Fragment key={i}>
          {part}
          {i < parts.length - 1 ? <br /> : null}
        </Fragment>
      ))}
    </>
  );
}
