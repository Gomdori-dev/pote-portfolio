import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = readFileSync(new URL('../src/lib/inquiry-draft.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText;
const values = new Map();
const scope = { exports:{}, window:{sessionStorage:{getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)}}};
vm.runInNewContext(compiled,scope);
const api=scope.exports;
const key='pote-inquiry-receipt:v1:["record-02",[],"buy"]';
const draft={at:Date.now(),type:'buy',pay:'payOnce',fields:{name:'보존 검수',email:'review@example.com',phone:'010-0000-0000',message:'여러 줄\n문의 내용'}};
let n=0; const check=fn=>{fn();n++;};
check(()=>assert.equal(api.saveInquiryDraft(key,draft),true));
check(()=>assert.equal(api.readInquiryDraft(key).fields.message,draft.fields.message));
check(()=>assert.equal(api.readInquiryDraft(key+'different'),null));
for(const change of [{at:Date.now()-31*60*1000},{at:Date.now()+120000},{at:0},{type:'bad'},{pay:'bad'},{fields:{message:'x'.repeat(6001)}},{fields:[]},{fields:{name:17}}])check(()=>assert.equal(api.parseInquiryDraft(JSON.stringify({...draft,...change})),null));
for(const raw of ['{bad','null','[]','x'.repeat(24001)])check(()=>assert.equal(api.parseInquiryDraft(raw),null));
check(()=>{api.saveInquiryDraft(key,{...draft,fields:{...draft.fields,consent:'true'}});assert.equal(api.readInquiryDraft(key).fields.consent,undefined);});
check(()=>{values.set(key.replace('receipt:','draft:'),JSON.stringify({...draft,at:1}));assert.equal(api.readInquiryDraft(key),null);assert.equal(values.size,0);});
check(()=>{api.saveInquiryDraft(key,draft);api.clearInquiryDraft(key);assert.equal(api.readInquiryDraft(key),null);});
Object.defineProperty(scope.window,'sessionStorage',{get(){throw Error('blocked');}});
check(()=>assert.equal(api.saveInquiryDraft(key,draft),false));
check(()=>assert.equal(api.readInquiryDraft(key),null));
check(()=>assert.doesNotThrow(()=>api.clearInquiryDraft(key)));
console.log(`문의 초안 검증 ${n}개 통과`);
